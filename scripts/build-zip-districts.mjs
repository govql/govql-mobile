#!/usr/bin/env node
// Builds src/data/zip-districts.ts from the Census ZCTA-to-congressional-district
// relationship file. Rerun when Census publishes a file for a new Congress:
//
//   node scripts/build-zip-districts.mjs [--congress 119] [--file local-copy.txt]
//
// Without --file it downloads the file for --congress (default 119) from census.gov.
// See plans/tasks/done/0006-zip-lookup.md for the decisions behind the output format.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const option = (name) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};

const congress = Number(option('congress') ?? 119);
const sourceUrl = `https://www2.census.gov/geo/docs/maps-data/data/rel2020/cd-sld/tab20_cd${congress}20_zcta520_natl.txt`;
const outPath = fileURLToPath(new URL('../src/data/zip-districts.ts', import.meta.url));

// State FIPS code → USPS code (50 states, DC, and the territories).
const FIPS = {
  '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT', '10': 'DE',
  '11': 'DC', '12': 'FL', '13': 'GA', '15': 'HI', '16': 'ID', '17': 'IL', '18': 'IN', '19': 'IA',
  '20': 'KS', '21': 'KY', '22': 'LA', '23': 'ME', '24': 'MD', '25': 'MA', '26': 'MI', '27': 'MN',
  '28': 'MS', '29': 'MO', '30': 'MT', '31': 'NE', '32': 'NV', '33': 'NH', '34': 'NJ', '35': 'NM',
  '36': 'NY', '37': 'NC', '38': 'ND', '39': 'OH', '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI',
  '45': 'SC', '46': 'SD', '47': 'TN', '48': 'TX', '49': 'UT', '50': 'VT', '51': 'VA', '53': 'WA',
  '54': 'WV', '55': 'WI', '56': 'WY', '60': 'AS', '66': 'GU', '69': 'MP', '72': 'PR', '78': 'VI',
};

async function loadSource() {
  const file = option('file');
  if (file) return readFile(file, 'utf8');
  const response = await fetch(sourceUrl);
  if (!response.ok) throw new Error(`Download failed (${response.status}): ${sourceUrl}`);
  return response.text();
}

/** "4807" → "TX7"; "5600" (at-large) and "1198" (delegate) → "WY0", "DC0"; "06ZZ" → null. */
function seat(geoid) {
  const state = FIPS[geoid.slice(0, 2)];
  const code = geoid.slice(2);
  if (!state) throw new Error(`Unknown state FIPS in ${geoid}`);
  if (code === 'ZZ') return null;
  const district = code === '00' || code === '98' ? 0 : Number(code);
  if (!Number.isInteger(district)) throw new Error(`Unexpected district code in ${geoid}`);
  return `${state}${district}`;
}

const text = (await loadSource()).replace(/^﻿/, '');
const [header, ...lines] = text.split(/\r?\n/);
const columns = header.split('|');
const col = (name) => {
  const i = columns.indexOf(name);
  if (i < 0) throw new Error(`Column ${name} not found; has the file format changed?`);
  return i;
};
const cdCol = col(`GEOID_CD${congress}_20`);
const zipCol = col('GEOID_ZCTA5_20');
const landCol = col('AREALAND_PART');

/** ZIP → [{ seat, land }] */
const parts = new Map();
for (const line of lines) {
  if (!line) continue;
  const cells = line.split('|');
  const zip = cells[zipCol];
  if (!zip) continue; // part of a district outside any ZCTA
  const s = seat(cells[cdCol]);
  if (!s) continue;
  if (!parts.has(zip)) parts.set(zip, []);
  parts.get(zip).push({ seat: s, land: Number(cells[landCol] || 0) });
}

const entries = [];
let multi = 0;
for (const zip of [...parts.keys()].sort()) {
  const list = parts.get(zip);
  // Drop zero-land parts, unless the ZIP has no land anywhere.
  const kept = list.some((p) => p.land > 0) ? list.filter((p) => p.land > 0) : list;
  const seats = [...new Set(kept.map((p) => p.seat))].sort((a, b) =>
    a.localeCompare(b, 'en', { numeric: true })
  );
  if (seats.length > 1) multi += 1;
  entries.push(`${zip}${seats.join(',')}`);
}

const today = new Date().toISOString().slice(0, 10);
const output = `// Generated by scripts/build-zip-districts.mjs on ${today}. Do not edit by hand.
// Source: ${sourceUrl}
// ${entries.length} ZIP codes (ZCTAs), ${multi} of them in more than one district.
// Format: entries separated by ";", each a 5-digit ZIP followed by its seats, e.g.
// "77002TX7,TX18" (district 0 = at-large or delegate).

/** The Congress these districts belong to. */
export const ZIP_DISTRICTS_CONGRESS = ${congress};

export const ZIP_DISTRICTS = ${JSON.stringify(entries.join(';'))};
`;

await writeFile(outPath, output);
console.log(`Wrote ${outPath}: ${entries.length} ZIPs, ${multi} multi-district, ${output.length} bytes`);
